#!/usr/bin/env node
/**
 * Regenerate staging-only search patch from the canonical 079 migration.
 * Source of truth: supabase/migrations/079_global_public_search.sql
 *
 * Includes helpers (forge_search_tokens …) + search_public_catalog.
 *
 *   node scripts/staging-only/sync-079-search-patch.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const srcPath = join(root, "supabase/migrations/079_global_public_search.sql");
const outPath = join(
  root,
  "scripts/staging-only/fix-079-search-public-catalog.sql",
);

const src = readFileSync(srcPath, "utf8");
const start = src.indexOf(
  "CREATE OR REPLACE FUNCTION public.forge_search_tokens(p_input text)",
);
const grantEndMarker =
  "GRANT EXECUTE ON FUNCTION public.search_public_catalog(text, integer)\n  TO anon, authenticated, service_role;";
const end = src.indexOf(grantEndMarker, start);
if (start < 0 || end < 0) {
  console.error(
    "ABORT: could not locate forge_search_tokens .. search_public_catalog in 079",
  );
  process.exit(1);
}
const body = src.slice(start, end + grantEndMarker.length);

const header = `-- STAGING ONLY — re-apply public search helpers + search_public_catalog from 079
-- Target: vuqpwvjvgyxffmvpfrxo only. Safe to re-run.
-- DO NOT edit this file by hand. Regenerate:
--   node scripts/staging-only/sync-079-search-patch.mjs
--
-- Short ASCII (SE/AI/UI/2D/3D): exact token / structured attrs only.
-- Noise 0: zzz-ia-seed-nohit-999 / seed nohit / zzz seed 999
-- Spot-check: SE → tag SE + SEキット基礎 only (no Seed/service noise)

`;

writeFileSync(outPath, `${header}${body}\n`);
console.log(`Wrote ${outPath} (${body.length} chars from 079)`);
